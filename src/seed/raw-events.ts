/**
 * Encodes seeded chain_events rows as the `getEvents` JSON shape used by
 * tests/fixtures/events.json, so `backfillEvents()` can rebuild the same
 * projections from bytes rather than trusting the database (#147).
 */
import { Address, nativeToScVal, xdr } from '@stellar/stellar-sdk';

const sym = (value: string) => xdr.ScVal.scvSymbol(value);
const u64 = (value: bigint | string) => nativeToScVal(BigInt(value), { type: 'u64' });
const u32 = (value: number) => nativeToScVal(value, { type: 'u32' });
const i128 = (value: bigint | string) => nativeToScVal(BigInt(value), { type: 'i128' });
const address = (value: string) => Address.fromString(value).toScVal();
const str = (value: string) => nativeToScVal(value, { type: 'string' });
const bytes = (hex: string) => nativeToScVal(Buffer.from(hex, 'hex'), { type: 'bytes' });

function map(entries: Record<string, xdr.ScVal>): xdr.ScVal {
  return xdr.ScVal.scvMap(
    Object.entries(entries).map(([key, val]) => new xdr.ScMapEntry({ key: sym(key), val })),
  );
}

/** Contract enum values (`Outcome`, `Category`) encode as vec[symbol]. */
const enumValue = (tag: string) => xdr.ScVal.scvVec([sym(tag)]);

export function encodeSeedEvent(event: any): any {
  const p = event.params ?? {};
  let topics: xdr.ScVal[];
  let value: xdr.ScVal;

  switch (event.eventName) {
    case 'Trade':
    case 'trade':
      topics = [sym('trade'), u64(p.market_id), address(p.trader)];
      value = map({
        outcome: enumValue(p.outcome?.tag ?? 'Yes'),
        is_buy: xdr.ScVal.scvBool(Boolean(p.is_buy)),
        collateral: i128(p.collateral),
        shares: i128(p.shares),
        fee: i128(p.fee),
        reserve_yes: i128(p.reserve_yes),
        reserve_no: i128(p.reserve_no),
      });
      break;
    case 'MarketCreated':
    case 'market_created':
      topics = [sym('market_created'), u64(p.market_id)];
      value = map({
        creator: address(p.creator),
        category: enumValue(p.category?.tag ?? 'Macro'),
        close_time: u64(p.close_time),
        seed_amount: i128(p.seed_amount),
        initial_yes_bps: u32(Number(p.initial_yes_bps)),
      });
      break;
    case 'MarketResolved':
    case 'market_resolved':
      topics = [sym('market_resolved'), u64(p.market_id)];
      value = map({
        outcome: p.outcome?.tag ? enumValue(p.outcome.tag) : xdr.ScVal.scvVoid(),
      });
      break;
    case 'TracePublished':
    case 'trace_published':
      topics = [sym('trace_published'), u64(p.trace_id), u64(p.market_id), address(p.agent)];
      value = map({
        action: str(String(p.action)),
        trace_hash: bytes(String(p.trace_hash)),
        ipfs_cid: str(String(p.ipfs_cid)),
        published_at: u64(p.published_at),
      });
      break;
    default:
      throw new Error(`No raw-event encoder for ${event.eventName}`);
  }

  return {
    type: 'contract',
    ledgerClosedAt: new Date(event.ledgerClosedAt).toISOString(),
    transactionIndex: 1,
    operationIndex: 0,
    inSuccessfulContractCall: true,
    id: event.id,
    ledger: event.ledger,
    txHash: event.txHash,
    contractId: event.contractId,
    topic: topics.map((topic) => topic.toXDR('base64')),
    value: value.toXDR('base64'),
  };
}

export function encodeSeedEvents(events: any[]): { _comment: string; events: any[] } {
  return {
    _comment: 'Generated by `npm run db:seed -- --with-raw-events`. Deterministic; do not commit secrets.',
    events: events.map(encodeSeedEvent),
  };
}
